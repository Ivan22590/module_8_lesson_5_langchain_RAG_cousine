"""Служебные (статусные) сообщения бота и правила их исключения из памяти.

Модуль вынесен отдельно, чтобы ``bot.py`` (отправляет эти тексты) и
``tools.py`` (не должен сохранять их в Pinecone) могли делить одни и те же
константы без циклических импортов.
"""

from __future__ import annotations

# Человекочитаемые статусы для вызываемых агентом инструментов.
TOOL_STATUS: dict[str, str] = {
    "search_knowledge_base": "🔍 Ищу в базе знаний…",
    "process_url_and_save": "🌐 Читаю статью и сохраняю…",
    "get_random_cat_fact": "🐱 Достаю факт о котике…",
    "save_user_memory": "💾 Запоминаю важный факт…",
}

WELCOME_MESSAGE = (
    "Привет! Я RAG-ассистент на LangChain.\n\n"
    "Я умею:\n"
    "• отвечать на вопросы по базе знаний (Pinecone);\n"
    "• изучать присланные ссылки и запоминать их содержимое;\n"
    "• хранить важные факты о вас;\n"
    "• рассказывать случайные факты о котиках.\n\n"
    "Команды:\n"
    "/reset — очистить историю диалога\n"
    "/help — эта справка"
)

HELP_MESSAGE = (
    "Просто напишите сообщение — я решу сам, что делать.\n"
    "Примеры:\n"
    "• «Изучи эту статью и запомни: https://example.com/post»\n"
    "• «Что ты знаешь о …?»\n"
    "• «Я живу в Питере» (я запомню это о вас)\n"
    "• «Расскажи факт о котиках»"
)

# Ответ бота на эхо собственного служебного сообщения.
SERVICE_ECHO_REPLY = (
    "⏭️ Служебное сообщение проигнорировано — в память оно не сохраняется."
)

# Служебные реплики бота (приветствие, справка, подтверждения, ошибки).
SERVICE_REPLIES: frozenset[str] = frozenset(
    {
        "🤔 Думаю…",
        "⚙️ Работаю…",
        "✅ Готово, отправляю ответ…",
        "✅ История диалога очищена.",
        "⚠️ Произошла ошибка при обработке запроса. Попробуйте позже.",
        SERVICE_ECHO_REPLY,
    }
)

# Префиксы, по которым текст однозначно считается служебным.
SERVICE_PREFIXES: tuple[str, ...] = (
    "🤔",
    "⚙️",
    "🌐",
    "🐱",
    "💾",
    "🔍",
    "✅",
    "⚠️",
    "Привет! Я RAG-ассистент",
    "Просто напишите сообщение",
)


def is_service_text(text: str | None) -> bool:
    """Проверить, является ли текст служебным ответом бота.

    Такие сообщения нельзя сохранять в долговременную память и передавать
    в агента как данные пользователя.
    """
    normalized = (text or "").strip()
    if not normalized:
        # Пустой текст — тоже не данные для сохранения.
        return True
    if normalized in SERVICE_REPLIES:
        return True
    if normalized in set(TOOL_STATUS.values()):
        return True
    # Персонализированное приветствие («Привет, Иван! Я RAG-ассистент…»)
    # тоже является служебным текстом бота.
    if "Я RAG-ассистент на LangChain" in normalized:
        return True
    return normalized.startswith(SERVICE_PREFIXES)
